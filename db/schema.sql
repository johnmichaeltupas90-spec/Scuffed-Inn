-- Scuffed Inn — final schema
-- Builds a fresh database (PostgreSQL 13+). Run once on an empty database, in
-- the Supabase SQL Editor or with psql. The files in db/migrations/ are
-- historical; they are not needed to build a new database.
--
-- Availability is decided by the reservation dates, not by a room status column.

BEGIN;

CREATE TABLE rooms (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number     bigint      NOT NULL UNIQUE,
    room_type       varchar     NOT NULL,
    price_per_night numeric(10, 2) NOT NULL,
    capacity        integer     NOT NULL,
    CONSTRAINT rooms_price_per_night_check CHECK (price_per_night >= 0),
    CONSTRAINT rooms_capacity_check CHECK (capacity > 0)
);

CREATE TABLE guests (
    id        uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name varchar(120) NOT NULL,
    email     varchar(200),
    phone     varchar(40)
);

-- The API reuses a guest by email, so the database enforces one row per address.
-- Guests without an email are allowed to repeat.
CREATE UNIQUE INDEX guests_email_lower_key
    ON guests (lower(email))
    WHERE email IS NOT NULL;

CREATE TABLE reservations (
    reservation_number bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         timestamptz NOT NULL DEFAULT now(),
    guest_id           uuid        NOT NULL REFERENCES guests(id) ON DELETE RESTRICT,
    room_id            bigint      NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    check_in           date        NOT NULL,
    check_out          date        NOT NULL,
    status             varchar(20) NOT NULL DEFAULT 'pending',
    payment_method     varchar(20),
    CONSTRAINT reservations_status_check
        CHECK (status IN ('pending', 'cancelled')),
    CONSTRAINT reservations_payment_method_check
        CHECK (payment_method IS NULL OR payment_method IN ('GCash', 'Maya', 'Card')),
    CONSTRAINT reservations_dates_check CHECK (check_out > check_in)
);

-- Supports the availability overlap query (room_id, check_in, check_out).
CREATE INDEX reservations_room_stay_idx
    ON reservations (room_id, check_in, check_out);

